// Helper to generate a square polygon centered around (lng, lat)
function createSquareGeoJSON(lat: number, lng: number, delta: number = 0.008): LandParcel['geojson'] {
  return {
    type: 'Polygon',
    coordinates: [
      [
        [lng - delta, lat - delta],
        [lng + delta, lat - delta],
        [lng + delta, lat + delta],
        [lng - delta, lat + delta],
        [lng - delta, lat - delta]
      ]
    ]
  };
}

